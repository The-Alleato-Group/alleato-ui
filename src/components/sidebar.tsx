const SIDEBAR_COOKIE_NAME = "sidebar_state";
const SIDEBAR_COOKIE_MAX_AGE = 60 * 60 * 24 * 7;
const SIDEBAR_WIDTH = "16rem";
// The mobile drawer pushes the page aside rather than covering it: the panel
// takes most of the viewport and the page slides right by the same amount, so
// a strip of it stays visible at the right edge. That strip is the way back --
// tapping it closes the drawer -- and the drawer's cast shadow on it is what
// says the nav is in front. One value drives both the panel's width and the
// page's translation, so they cannot drift apart. `22rem` keeps the strip wide
// enough to read on a small tablet (`useIsMobile()` picks this branch up to
// `md`), and sits under SheetContent's own `sm:max-w-sm` cap.
const SIDEBAR_WIDTH_MOBILE = "min(82vw, 22rem)";
const SIDEBAR_WIDTH_ICON = "3.5rem";
const SIDEBAR_KEYBOARD_SHORTCUT = "b";

type SidebarContextProps = {
  state: "expanded" | "collapsed";
  open: boolean;
  setOpen: (open: boolean) => void;
  openMobile: boolean;
  setOpenMobile: (open: boolean) => void;
  isMobile: boolean;
  toggleSidebar: () => void;
};

const SidebarContext = React.createContext<SidebarContextProps | null>(null);

function useSidebar() {
  const context = React.useContext(SidebarContext);
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.");
  }

  return context;
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean;
  open?: boolean;
  onOpenChange?: (open: boolean) => void;
}) {
  const isMobile = useIsMobile();
  const [openMobile, setOpenMobile] = React.useState(false);

  // This is the internal state of the sidebar.
  // We use openProp and setOpenProp for control from outside the component.
  const [_open, _setOpen] = React.useState(defaultOpen);
  const open = openProp ?? _open;
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value;
      if (setOpenProp) {
        setOpenProp(openState);
      } else {
        _setOpen(openState);
      }

      // This sets the cookie to keep the sidebar state.
      document.cookie = `${SIDEBAR_COOKIE_NAME}=${openState}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`;
    },
    [setOpenProp, open],
  );

  // Helper to toggle the sidebar.
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open);
  }, [isMobile, setOpen, setOpenMobile]);

  // Adds a keyboard shortcut to toggle the sidebar.
  React.useEffect(() => {
    const handleKeyDown = (event: KeyboardEvent) => {
      if (
        event.key === SIDEBAR_KEYBOARD_SHORTCUT &&
        (event.metaKey || event.ctrlKey)
      ) {
        event.preventDefault();
        toggleSidebar();
      }
    };

    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [toggleSidebar]);

  // We add a state so that we can do data-state="expanded" or "collapsed".
  // This makes it easier to style the sidebar with Tailwind classes.
  const state = open ? "expanded" : "collapsed";

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar],
  );

  return (
    <SidebarContext.Provider value={contextValue}>
      <TooltipProvider delayDuration={0}>
        <div
          data-slot="sidebar-wrapper"
          // `data-mobile-nav` is what `SidebarInset` reads to push the page
          // aside; the sheet itself is portalled to <body>, so it cannot see
          // this attribute or these variables and carries its own copy.
          data-mobile-nav={isMobile && openMobile ? "open" : "closed"}
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH,
              "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
              "--sidebar-width-mobile": SIDEBAR_WIDTH_MOBILE,
              ...style,
            } as React.CSSProperties
          }
          className={cn(
            "group/sidebar-wrapper has-data-[variant=inset]:bg-sidebar flex min-h-svh w-full",
            // The pushed page overhangs the viewport by the drawer's width;
            // clip it so the document never grows a horizontal scrollbar.
            "data-[mobile-nav=open]:overflow-x-clip",
            className,
          )}
          {...props}
        >
          {children}
        </div>
      </TooltipProvider>
    </SidebarContext.Provider>
  );
}

function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  className,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right";
  variant?: "sidebar" | "floating" | "inset";
  collapsible?: "offcanvas" | "icon" | "none";
}) {
  const { isMobile, state, openMobile, setOpenMobile } = useSidebar();

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "bg-sidebar text-sidebar-foreground flex h-full w-[var(--sidebar-width)] flex-col",
          className,
        )}
        {...props}
      >
        {children}
      </div>
    );
  }

  if (isMobile) {
    return (
      <Sheet open={openMobile} onOpenChange={setOpenMobile} {...props}>
        <SheetContent
          data-sidebar="sidebar"
          data-slot="sidebar"
          data-mobile="true"
          // THE SCRIM STAYS MOUNTED, but transparent. It is the overlay that
          // turns a tap on the visible strip of page into "close" (Radix
          // dismisses on pointer-down outside the content, and the overlay is
          // what receives that pointer-down while the page beneath has
          // `pointer-events: none` from the modal scroll lock). What it no
          // longer does is dim: the pushed page is meant to read as the page,
          // one tap from coming back, and the drawer's cast shadow
          // (`--shadow-drawer`) carries the layering instead. The previous
          // `bg-black/50` scrim also tinted iOS Safari's own chrome until
          // theme-color was declared (see `ThemeColorMeta`); a transparent
          // scrim cannot.
          //
          // The drawer is full-height under `viewportFit: "cover"` (see
          // app/layout.tsx), so it spans the display cutout at BOTH ends and
          // has to inset its content from each:
          //   `pb-[env(safe-area-inset-bottom)]` — without it the footer's
          //     account row sits under the iOS home indicator and cannot be
          //     tapped reliably.
          //   `pt-[env(safe-area-inset-top)]` — without it the header's logo
          //     and close button sit under the status bar and notch. The
          //     header's own `pt-5` is a fixed 20px and does not reach a
          //     47-59px inset, so this was the other half of the reported
          //     "cut off at the top". Padding sits inside `h-dvh`
          //     (border-box), so reserving it shifts the content down without
          //     changing the panel's height or its bottom edge.
          //
          // `h-dvh` is the ONE source of truth for the drawer's height, and it
          // has to be an explicit height rather than `inset-y-0`: on a fixed
          // element `inset-y-0` resolves against the *large* viewport, so on iOS
          // Safari the panel runs on underneath the browser's bottom toolbar.
          // `h-dvh` tracks the viewport as those bars come and go. This does not
          // fight the `inset-y-0` that `SheetContent` applies for `side="left"`
          // (tailwind-merge cannot strip it): for a fixed element an explicit
          // height wins over `top` + `bottom` whatever order they land in.
          //
          // `gap-0` drops SheetContent's `gap-4`, and this element is the
          // drawer's only scroll container — see the column below.
          //
          // `shadow-(--shadow-drawer)` replaces SheetContent's `shadow-sm`. It
          // has to be the `-(--var)` form: tailwind-merge cannot tell whether
          // `shadow-[var(--x)]` is a shadow or a shadow *color*, keeps both,
          // and `shadow-sm` then wins on source order (verified 2026-09-16). The
          // drawer's own enter/exit animation and the page's push in
          // `SidebarInset` share one easing and duration pair, so the two
          // edges move together.
          className={cn(
            "bg-sidebar text-sidebar-foreground h-dvh w-[var(--sidebar-width)] gap-0 rounded-none border-0 p-0 pt-[env(safe-area-inset-top)] pb-[env(safe-area-inset-bottom)] shadow-(--shadow-drawer) [&>button]:hidden",
            className,
          )}
          overlayClassName="bg-transparent"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH_MOBILE,
            } as React.CSSProperties
          }
          side={side}
        >
          <SheetHeader className="sr-only">
            <SheetTitle>Sidebar</SheetTitle>
            <SheetDescription>Displays the mobile sidebar.</SheetDescription>
          </SheetHeader>
          {/* This column is the drawer's whole content, and the sheet above is
              its only scrollport. `h-full` is a floor, not a cap: a flex item's
              `min-height` is `auto`, so a nav list taller than the viewport
              grows this past 100% and the sheet scrolls it. That is what keeps
              the footer's `mt-auto` honest — bottom-anchored while the nav is
              short, flowing after it once it is long — instead of pinning an
              opaque block over a list clipped mid-row. */}
          <div className="flex h-full w-full flex-col">{children}</div>
        </SheetContent>
      </Sheet>
    );
  }

  return (
    <div
      className="group peer text-sidebar-foreground hidden md:block"
      data-state={state}
      data-collapsible={state === "collapsed" ? collapsible : ""}
      data-variant={variant}
      data-side={side}
      data-slot="sidebar"
      {...props}
    >
      {/* This is what handles the sidebar gap on desktop */}
      {/* Gap stays at icon width even during hover-expand (overlay, not push) */}
      <div
        data-slot="sidebar-gap"
        className={cn(
          "relative w-[var(--sidebar-width)] bg-transparent transition-[width] duration-300 ease-in-out",
          "group-data-[collapsible=offcanvas]:w-0",
          "group-data-[side=right]:rotate-180",
          variant === "floating" || variant === "inset"
            ? "group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+1rem)]"
            : "group-data-[collapsible=icon]:w-[var(--sidebar-width-icon)]",
        )}
      />
      {/* Sidebar container: expands to full width on hover-expand (overlays content) */}
      <div
        data-slot="sidebar-container"
        className={cn(
          "fixed inset-y-0 z-[100] hidden h-svh w-[var(--sidebar-width)] transition-[left,right,width] duration-300 ease-in-out md:flex",
          side === "left"
            ? "left-0 group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)]"
            : "right-0 group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)]",
          // Adjust the padding for floating and inset variants.
          variant === "floating" || variant === "inset"
            ? "p-2 group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+1rem+2px)]"
            : // Edge elevation instead of a 1px rule: at rest the nav occupies its
              // own column in the layout, so it only has to read as a layer above
              // the canvas -- nothing is behind it to be separated from.
              cn(
                "group-data-[collapsible=icon]:w-[var(--sidebar-width-icon)]",
                side === "left"
                  ? "shadow-[var(--shadow-edge)]"
                  : "shadow-[var(--shadow-edge-inverse)]",
              ),
          // Hover-expand: container goes to full width while gap stays at icon width
          "group-data-[hover-expanded=true]:w-[var(--sidebar-width)] group-data-[hover-expanded=true]:z-[110]",
          // ...but while it peeks it leaves the layout and floats OVER the page,
          // and the resting edge is tuned to be almost invisible on purpose, so
          // the overlay had no discernible boundary -- you could not see where
          // the nav stopped and the page began (Megan, 2026-09-23). The peek
          // state therefore gets its own deeper edge plus a 1px rule to
          // terminate the panel, the same argument --shadow-drawer already makes
          // for the mobile drawer, at a lighter weight because this panel is
          // transient and covers less.
          //
          // Two stacked `group-data-*` variants would compile to a DESCENDANT
          // chain and never match one element carrying both attributes, so the
          // side split is done here in JS, where `side` is already in scope.
          side === "left"
            ? "group-data-[hover-expanded=true]:shadow-[var(--shadow-edge-overlay)] group-data-[hover-expanded=true]:border-r group-data-[hover-expanded=true]:border-sidebar-border"
            : "group-data-[hover-expanded=true]:shadow-[var(--shadow-edge-overlay-inverse)] group-data-[hover-expanded=true]:border-l group-data-[hover-expanded=true]:border-sidebar-border",
          className,
        )}
      >
        <div
          data-sidebar="sidebar"
          data-slot="sidebar-inner"
          className="bg-sidebar relative flex h-full w-full flex-col group-data-[variant=floating]:border-sidebar-border group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:border group-data-[variant=floating]:shadow-sm"
        >
          {children}
        </div>
      </div>
    </div>
  );
}

function SidebarTrigger({
  className,
  onClick,
  ...props
}: React.ComponentProps<typeof Button>) {
  const { toggleSidebar } = useSidebar();

  return (
    <Button
      data-sidebar="trigger"
      data-slot="sidebar-trigger"
      variant="ghost"
      size="icon"
      className={cn("size-7", className)}
      onClick={(event) => {
        onClick?.(event);
        toggleSidebar();
      }}
      {...props}
    >
      <PanelLeftIcon />
      <span className="sr-only">Toggle Sidebar</span>
    </Button>
  );
}

