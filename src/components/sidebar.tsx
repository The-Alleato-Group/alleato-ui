function SidebarInset({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="sidebar-inset"
      className={cn(
        "bg-background relative z-0 isolate flex w-full flex-1 flex-col",
        "md:peer-data-[variant=inset]:m-2 md:peer-data-[variant=inset]:ml-0 md:peer-data-[variant=inset]:rounded-xl md:peer-data-[variant=inset]:shadow-sm md:peer-data-[variant=inset]:peer-data-[state=collapsed]:ml-2",
        // Mobile push: while the drawer is open the whole page -- header,
        // content, and the fixed bottom bar, which a transformed ancestor
        // carries along -- slides right by the drawer's width. The translate is
        // applied only in the open state rather than held at 0 when closed,
        // because any `translate` value other than `none` turns this element
        // into the containing block for its fixed descendants, and the bottom
        // bar must dock to the real viewport the rest of the time. Easing and
        // durations mirror `SheetContent` (400ms in, 250ms out).
        "transition-[translate] ease-[cubic-bezier(0.22,1,0.36,1)] duration-[250ms]",
        "group-data-[mobile-nav=open]/sidebar-wrapper:translate-x-[var(--sidebar-width-mobile)] group-data-[mobile-nav=open]/sidebar-wrapper:duration-[400ms]",
        className,
      )}
      {...props}
    />
  );
}

